"""FFmpeg reveal: original photo → white flash + SFX → animated Halloween clip.

Usage:
    python -m pipeline.reveal before.jpg after.mp4 -o out.mp4
    python -m pipeline.reveal before.jpg after.png -o out.mp4   # fallback without I2V (zoom + flicker)
    python -m pipeline.reveal before.jpg after.mp4 -o out.mp4 --hold 1.2 --after-dur 3.5
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

FPS = 24
# "auto": frame at the photo's proportions (short side 1080 px), ratio clamped to [4:5, 16:9] → no bars
# for a photo between 4:5 and 16:9 (3:2, 4:3, 1:1…); beyond that, blurred bars.
FORMATS = {"auto": None, "4:5": (1080, 1350), "16:9": (1920, 1080)}
AUTO_RATIO = (4 / 5, 16 / 9)
SHORT_SIDE = 1080
IMAGE_EXTS = {".png", ".jpg", ".jpeg", ".webp"}


@dataclass(frozen=True)
class RevealConfig:
    fmt: str = "auto"
    background: str = "blur"  # "blur" or "black" (margins); never crops the subject
    hold: float = 1.5  # duration of the original photo, flash included
    flash_in: float = 0.12  # fade to white
    flash_out: float = 0.35  # fade from white; also hides frame 0 regenerated by LTX
    after: float = 4.0  # max duration of the "after" part
    still_zoom: float = 0.06  # fallback: total zoom over the duration


def probe_duration(path: Path) -> float:
    out = subprocess.run(
        ["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "json", str(path)],
        check=True, capture_output=True, text=True,
    ).stdout
    return float(json.loads(out)["format"]["duration"])


def probe_size(path: Path) -> tuple[int, int]:
    out = subprocess.run(
        ["ffprobe", "-v", "error", "-select_streams", "v:0", "-show_entries", "stream=width,height", "-of", "json", str(path)],
        check=True, capture_output=True, text=True,
    ).stdout
    s = json.loads(out)["streams"][0]
    return s["width"], s["height"]


def frame_size(fmt: str, before: Path) -> tuple[int, int]:
    if FORMATS[fmt]:
        return FORMATS[fmt]
    w, h = probe_size(before)
    r = min(max(w / h, AUTO_RATIO[0]), AUTO_RATIO[1])
    long_side = round(SHORT_SIDE * max(r, 1 / r) / 2) * 2  # yuv420p: even dimensions
    return (long_side, SHORT_SIDE) if r >= 1 else (SHORT_SIDE, long_side)


def _fit(src: str, dst: str, w: int, h: int, background: str) -> str:
    """Fits `src` into a w×h frame without cropping: blurred background or black margins."""
    fg = f"scale={w}:{h}:force_original_aspect_ratio=decrease:force_divisible_by=2,setsar=1"
    if background == "black":
        return f"[{src}]{fg},pad={w}:{h}:(ow-iw)/2:(oh-ih)/2:color=black[{dst}]"
    return (
        f"[{src}]split[{dst}_bg][{dst}_fg];"
        f"[{dst}_bg]scale={w}:{h}:force_original_aspect_ratio=increase,crop={w}:{h},"
        f"boxblur=40:2,eq=brightness=-0.08,setsar=1[{dst}_bgb];"
        f"[{dst}_fg]{fg}[{dst}_fgs];"
        f"[{dst}_bgb][{dst}_fgs]overlay=(W-w)/2:(H-h)/2[{dst}]"
    )


def _sfx_filter(idx: int | None, cut: float, total: float) -> str:
    """Whoosh peaking on the cut + low thump; or a provided SFX, aligned on the cut.

    20 ms attack on the thump and loudnorm at -18 LUFS: the thump without attack, ×4 gain then limiter, clicked
    (A/B of Oct 28).
    """
    if idx is not None:
        delay = int(max(cut - 0.3, 0) * 1000)
        return f"[{idx}:a]aformat=sample_rates=48000:channel_layouts=stereo,adelay={delay}:all=1,apad,atrim=0:{total}[aout]"
    rise = 0.35
    delay = int((cut - rise) * 1000)
    return (
        f"anoisesrc=d=1.2:c=pink:a=0.3:r=48000,highpass=f=300,lowpass=f=2500,"
        f"afade=t=in:d={rise}:curve=qsin,afade=t=out:st={rise}:d=0.8,adelay={delay}:all=1[whoosh];"
        f"sine=f=55:d=0.9:r=48000,volume=0.8,afade=t=in:d=0.02,afade=t=out:st=0.05:d=0.85,"
        f"adelay={int(cut * 1000)}:all=1[thump];"
        f"[whoosh][thump]amix=inputs=2:normalize=0,loudnorm=I=-18:TP=-3:LRA=11,"
        f"aformat=sample_rates=48000:channel_layouts=stereo,apad,atrim=0:{total}[aout]"
    )


def build_command(before: Path, after: Path, out: Path, sfx: Path | None, cfg: RevealConfig) -> list[str]:
    w, h = frame_size(cfg.fmt, before)
    still = after.suffix.lower() in IMAGE_EXTS
    after_dur = cfg.after if still else min(cfg.after, probe_duration(after))
    total = cfg.hold + after_dur
    n_after = round(after_dur * FPS)

    inputs = ["-loop", "1", "-framerate", str(FPS), "-t", f"{cfg.hold}", "-i", str(before)]
    inputs += ["-i", str(after)]  # still image: a single frame, zoompan duplicates it
    if sfx:
        inputs += ["-i", str(sfx)]

    v = [
        _fit("0:v", "b0", w, h, cfg.background),
        f"[b0]format=yuv420p,fade=t=out:st={cfg.hold - cfg.flash_in}:d={cfg.flash_in}:color=white[before]",
    ]
    if still:
        # Fallback: slow centered zoom + flickering light. ×2 upscale before zoompan against jitter.
        z = cfg.still_zoom
        v += [
            _fit("1:v", "a0", w, h, cfg.background),
            f"[a0]scale={2 * w}:{2 * h},zoompan=z='1+{z}*on/{n_after}':d={n_after}"
            f":x='iw/2-iw/zoom/2':y='ih/2-ih/zoom/2':s={w}x{h}:fps={FPS},"
            f"eq=brightness='0.035*sin(2*PI*t*1.3)*sin(2*PI*t*7.1)':eval=frame,vignette=PI/5[a1]",
        ]
    else:
        v += [
            _fit("1:v", "a0", w, h, cfg.background),
            f"[a0]fps={FPS},trim=duration={after_dur},setpts=PTS-STARTPTS[a1]",
        ]
    v += [
        f"[a1]format=yuv420p,fade=t=in:st=0:d={cfg.flash_out}:color=white[after]",
        "[before][after]concat=n=2:v=1:a=0[vout]",
        _sfx_filter(2 if sfx else None, cfg.hold, total),
    ]

    return [
        "ffmpeg", "-y", "-hide_banner", "-loglevel", "error", "-filter_complex_threads", "2", *inputs,
        "-filter_complex", ";".join(v),
        "-map", "[vout]", "-map", "[aout]",  # the audio track generated by LTX is ignored
        "-c:v", "libx264", "-threads", "2", "-preset", "medium", "-crf", "18", "-pix_fmt", "yuv420p", "-r", str(FPS),
        "-c:a", "aac", "-b:a", "192k", "-t", f"{total}", "-movflags", "+faststart", str(out),
    ]


def make_reveal(before: Path, after: Path, out: Path, sfx: Path | None = None, cfg: RevealConfig = RevealConfig()) -> Path:
    out.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(build_command(before, after, out, sfx, cfg), check=True)
    return out


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")  # Windows cp1252 console: the docstring contains "→"
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("before", type=Path, help="original photo")
    p.add_argument("after", type=Path, help="I2V clip (.mp4) or Halloween image (fallback)")
    p.add_argument("-o", "--out", type=Path, required=True)
    p.add_argument("--sfx", type=Path, help="SFX to align on the cut (default: synthetic whoosh)")
    p.add_argument("--format", dest="fmt", choices=FORMATS, default="auto")
    p.add_argument("--background", choices=["blur", "black"], default="blur")
    p.add_argument("--hold", type=float, default=1.5, help="duration of the original photo before the flash (s)")
    p.add_argument("--after-dur", type=float, default=4.0, help="max duration of the \"after\" part (s)")
    a = p.parse_args()
    cfg = RevealConfig(fmt=a.fmt, background=a.background, hold=a.hold, after=a.after_dur)
    print(make_reveal(a.before, a.after, a.out, a.sfx, cfg))


if __name__ == "__main__":
    main()
